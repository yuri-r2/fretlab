const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const source = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8')
  .replace('/* ---------- boot ---------- */', 'window.__D = { S, VO, P, M, TABS, ROUTINES, rtBlocks };\n/* ---------- boot ---------- */');
const tmp = path.join(os.tmpdir(), 'fretlab-desktop.html');
const artifact = path.join(os.tmpdir(), 'fretlab-artifact-desktop.html');
fs.writeFileSync(tmp, source);
fs.writeFileSync(artifact, '<!doctype html><html><body>' + source.match(/<body>([\s\S]*?)<\/body>/)[1] + '</body></html>');
(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, colorScheme: 'light' });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('file://' + tmp);
    assert.equal(await page.locator('.tab').count(), 4);
    assert.equal(await page.locator('#view-riffs, #dRoll').count(), 0);
    assert.equal(await page.locator('[data-tab="riffs"]').count(), 0);
    await page.click('.tab[data-tab="library"]');
    await page.click('#view-library [data-go="voicings"]');
    assert.ok(await page.locator('#chordGrid .chord-card').count() > 0);
    assert.equal(await page.locator('#voSearch, #voStyle').count(), 0);
    await page.click('#chordGroup [data-group="movable"]');
    await page.selectOption('#chordRoot','9');
    await page.selectOption('#chordGenre','jazz');
    await page.selectOption('#chordLabels','degree');
    const preview = page.locator('#chordCards [data-chord-sound]').first();
    await preview.click(); assert.equal(await preview.getAttribute('aria-pressed'),'true');
    await page.waitForTimeout(1600);await page.reload();
    assert.equal(await page.locator('#chordGroup [data-group="movable"]').getAttribute('aria-pressed'),'true');
    assert.equal(await page.locator('#chordGenre').inputValue(),'jazz');
    assert.equal(await page.locator('#chordLabels').inputValue(),'degree');
    assert.equal(await page.locator('#chordRoot').inputValue(),'9');
    await page.locator('#chordCards [data-chord-sound]').first().click();
    await page.click('.tab[data-tab="today"]');
    assert.equal(await page.evaluate(() => window.__D.VO.bus), null, 'leaving the reference stops preview audio');
    await page.click('.tab[data-tab="library"]');
    await page.click('#view-library [data-go="exercises"]');
    await page.fill('#exSearch', 'A-string major, minor and sus shapes');
    await page.click('[data-ex="v_shape_a"]');
    await page.click('#pSteps [data-step="1"]');
    for (const width of [1280, 1440, 1920]) {
      await page.setViewportSize({ width, height: 960 });
      const canvas = await page.locator('#pCanvas').boundingBox();
      const feedback = await page.locator('#pFeedback').boundingBox();
      const nav = await page.locator('.tabs').boundingBox();
      assert.ok(canvas.width >= 530 && feedback.x > canvas.x + canvas.width, `side-by-side workspace at ${width}`);
      assert.ok(feedback.y < 500 && nav.x + nav.width < canvas.x, `feedback and navigation stay accessible at ${width}`);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    }
    const ctl = await page.locator('#pCtl').boundingBox(), cv = await page.locator('#pCanvas').boundingBox();
    assert.ok(ctl.y + ctl.height <= cv.y && await page.locator('#pLoop').isVisible() && await page.locator('#pLabSeg').isVisible(), 'playback and display controls sit open above the tab');
    await page.focus('#pPlay');
    await page.keyboard.press('Space');
    assert.equal(await page.locator('#pPlay').textContent(), 'Pause');
    await page.keyboard.press('Space');
    assert.equal(await page.locator('#pPlay').textContent(), 'Play');
    const light = await page.locator('#pCanvas').evaluate(n => Array.from(n.getContext('2d').getImageData(2,2,1,1).data));
    await page.emulateMedia({ colorScheme: 'dark' });
    await page.waitForFunction(() => { const n = document.querySelector('#pCanvas'); return n.getContext('2d').getImageData(2,2,1,1).data[0] < 80; });
    const dark = await page.locator('#pCanvas').evaluate(n => Array.from(n.getContext('2d').getImageData(2,2,1,1).data));
    assert.ok(light[0] > 200 && dark[0] < 80, 'notation follows a live appearance change');
    await page.click('#openSettings');
    await page.focus('#closeSettings');
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.locator('#sReset').evaluate(n => n === document.activeElement), true);
    await page.keyboard.press('Tab');
    assert.equal(await page.locator('#closeSettings').evaluate(n => n === document.activeElement), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#settings').isVisible(), false);
    assert.equal(await page.locator('#openSettings').evaluate(n => n === document.activeElement), true);
    await page.selectOption('#pKey', '9');
    await page.click('#pBack');
    assert.equal(await page.locator('#exLib').isVisible(), true, 'return goes back to Exercises');
    const validRoutines = await page.evaluate(() => {
      const { TABS, ROUTINES, rtBlocks } = window.__D;
      return Object.keys(ROUTINES).every(k => rtBlocks(k).every(b => TABS.includes(b.tool)));
    });
    assert.equal(validRoutines, true, 'routines have no removed destinations');
    await page.click('.tab[data-tab="library"]');
    await page.click('#view-library [data-go="exercises"]');
    await page.fill('#exSearch', 'no-such-exercise');
    assert.equal(await page.locator('#exList [data-ex]').count(), 0);
    await page.click('#exClearSearch');
    assert.ok(await page.locator('#exList [data-ex]').count() > 0);
    await page.evaluate(() => { const state = window.__D.S; state.riffs = [{id:'legacy-idea',name:'An earlier idea'}]; localStorage.setItem('fretlab.v1', JSON.stringify(state)); });
    await page.goto('file://' + tmp + '?legacy=1#riffs');
    assert.equal(await page.locator('#view-voicings').isVisible(), true, 'old links lead to chord practice');
    assert.equal(await page.evaluate(() => window.__D.S.riffs[0].id), 'legacy-idea', 'older saved ideas remain in backups');
    await page.goto('file://' + artifact + '#exercises');
    await page.click('#exList [data-ex="triads"]');
    assert.equal(await page.locator('#pNextStep').isVisible(), false, 'body-only deployment preserves hidden controls');
    assert.equal(await page.locator('#view-progress').isVisible(), false);
    assert.deepEqual(errors, []);
    console.log('Desktop workspace at 1280/1440/1920, reference preferences and previews, exercise search, appearance changes, keyboard controls, return context, removed destinations and body-only deployment: OK');
  } finally { await browser.close(); fs.unlinkSync(tmp); fs.unlinkSync(artifact); }
})().catch(e => { console.error(e); process.exitCode = 1; });
