const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const source = fs.readFileSync(path.join(__dirname, '..', 'index.html'), 'utf8')
  .replace('/* ---------- boot ---------- */', `window.__T = { EX, P, S, AU, exOpen, exStart, exStop, exPause, exPos, exSeek, exSched, exSync, exFrame, exReanchor, exListen, exSetSpot, exCount, exLabel };
/* ---------- boot ---------- */`);
const tmp = path.join(os.tmpdir(), 'fretlab-transport.html');
fs.writeFileSync(tmp, source);
(async () => {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('file://' + tmp);
    await page.evaluate(() => { const t = window.__T; t.exOpen('triads', 0); t.S.ui.exopts.count = false; });
    assert.equal(await page.locator('#pFingers').isChecked(), true);
    assert.ok(await page.locator('#pBoard .fb-finger').count()>0, 'finger suggestions accompany fretboard degree labels');
    const withFingers = await page.locator('#pCanvas').evaluate(n => n.toDataURL());
    await page.uncheck('#pFingers');
    assert.equal(await page.locator('#pFingerHint').isVisible(), false);
    assert.equal(await page.locator('#pBoard .fb-finger').count(),0, 'the toggle hides fretboard finger annotations');
    assert.notEqual(await page.locator('#pCanvas').evaluate(n => n.toDataURL()), withFingers, 'finger numbers are optional alongside degree labels');
    assert.equal(await page.locator('#pLab').inputValue(), 'degree', 'finger toggle retains the selected note labels');
    await page.check('#pFingers');
    assert.equal(await page.locator('#pFingerHint').isVisible(), true);
    await page.click('#pPlay');
    await page.waitForTimeout(500);
    assert.equal(await page.evaluate(() => window.__T.P.running), true, 'following the playhead does not trigger seeking');
    await page.click('#pPlay');
    const paused = await page.evaluate(() => window.__T.P.viewPos);
    assert.ok(paused > 0.2);
    await page.waitForTimeout(200);
    assert.equal(await page.evaluate(() => window.__T.P.viewPos), paused, 'pause retains the exact position');
    assert.equal(await page.locator('#pPlay').textContent(), 'Resume');
    await page.click('#pPlay');
    assert.ok(await page.evaluate(p => window.__T.exPos() >= p, paused), 'resume starts at the paused position');
    await page.locator('#pScroll').evaluate(el => { el.value = el.max / 2; el.dispatchEvent(new Event('input', {bubbles:true})); });
    await page.waitForTimeout(100);
    assert.equal(await page.evaluate(() => window.__T.P.running), false, 'scrolling pauses playback at the chosen spot');
    assert.ok(await page.evaluate(() => window.__T.P.viewPos > window.__T.P.L / 3));
    await page.locator('#pCanvas').dispatchEvent('wheel', { deltaX: -190, deltaY: 0 });
    const scrolled = await page.evaluate(() => window.__T.P.viewPos);
    const canvas = await page.locator('#pCanvas').boundingBox();
    await page.mouse.click(canvas.x + 380, canvas.y + 95);
    const clicked = await page.evaluate(() => ({ pos: window.__T.P.viewPos, times: window.__T.P.ev.map(e => e.t) }));
    assert.ok(clicked.pos > scrolled && clicked.times.some(t => Math.abs(t - clicked.pos) < 1e-6), 'clicking the tab selects an actual note');
    await page.focus('#pScroll');
    await page.keyboard.press('Home');
    assert.equal(await page.evaluate(() => window.__T.P.viewPos), 0);
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.evaluate(() => window.__T.P.viewPos), 1, 'position slider supports keyboard navigation');
    await page.click('#pRestart');
    assert.equal(await page.evaluate(() => window.__T.P.viewPos), 0);
    const failures = await page.evaluate(() => {
      const { EX, P, S, AU, exOpen, exStart, exStop, exPause, exPos, exSeek, exSched, exSync, exFrame, exReanchor, exListen, exSetSpot, exCount } = window.__T;
      const failures = [], check = (ok, message) => { if (!ok) failures.push(message); };
      exStop();
      let now = AU.ctx.currentTime;
      Object.defineProperty(AU.ctx, 'currentTime', { configurable: true, get: () => now });
      EX.push({id:'transport_test',cat:'Technique',title:'Transport timing',keyed:'maj',key0:0,steps:[{n:'Timing',d:'',bpm:120,goal:180,goal0:180,bar:4,build:key=>({L:8,ev:Array.from({length:16},(_,i)=>({t:i/2,d:0.5,n:[{s:0,f:key,fg:1}]}))})}]});
      exOpen('transport_test',0);
      Object.assign(S.ui.exopts,{count:false,loop:true,guide:true,click:true,keycycle:false,ladder:true});
      exStart(); clearInterval(P.timer); cancelAnimationFrame(P.frame);
      const audio = P.bus, clickBus = P.cbus, start = P.startT, startBpm = P.bpm;
      let boundary = start + P.L * 60 / startBpm;
      now = boundary - 0.12; exSched();
      check(P.loopQueue.length === 1, 'next loop is prepared before the boundary');
      const next = P.loopQueue[0];
      check(next.bpm === startBpm + 4 && next.startT === boundary, '+4 bpm takes effect precisely at the boundary');
      check(next.i > 0 && next.cb > 0, 'the first guide note and click are scheduled ahead of the new loop');
      check(P.bpm === startBpm, 'display tempo stays on the current loop until the boundary');
      now = boundary + 0.001; exSync();
      check(P.bpm === startBpm + 4, 'display tempo changes at the boundary');
      check(P.bus === audio && P.cbus === clickBus, 'automatic tempo changes preserve sounding and scheduled audio');
      for (let i = 0; i < 4; i++) {
        boundary = P.audio.startT + P.audio.data.L * 60 / P.audio.bpm;
        now = boundary - 0.12; exSched();
        check(P.loopQueue[0] && Math.abs(P.loopQueue[0].startT - boundary) < 1e-9, 'successive loops stay on the audio clock');
        now = boundary + 0.001; exSync();
      }
      exPause();
      Object.assign(S.ui.exopts,{ladder:false,keycycle:true});
      exOpen('triads',0); exStart(); clearInterval(P.timer); cancelAnimationFrame(P.frame);
      const keys = [P.keyPc], keyBus = P.bus;
      for (let i = 0; i < 12; i++) {
        boundary = P.audio.startT + P.audio.data.L * 60 / P.audio.bpm;
        now = boundary - 0.12; exSched();
        check(P.loopQueue.length === 1 && P.loopQueue[0].i > 0, 'new-key first note is scheduled before its boundary');
        now = boundary + 0.001; exSync(); keys.push(P.keyPc);
        check(P.ev[0].n.every(n => Number.isFinite(n.f)), 'new-key fingering is valid');
      }
      check(new Set(keys.slice(0,12)).size === 12 && keys[12] === keys[0], 'existing key cycling still covers all twelve keys');
      check(P.bus === keyBus, 'key transitions keep the audio bus connected');
      exStop(); S.ui.exopts.keycycle = false; S.ui.exopts.loop = false; S.ui.exopts.count = true;
      exSeek(4); exStart(); clearInterval(P.timer); cancelAnimationFrame(P.frame);
      check(exPos() === 4 && exCount() > 3.9, 'a mid-exercise start counts in at the chosen spot');
      now = P.countUntil + 0.2; const beforePause = exPos(); exPause();
      check(Math.abs(P.viewPos - beforePause) < 1e-6, 'pause stores the audio-clock position');
      exStart(); clearInterval(P.timer); cancelAnimationFrame(P.frame);
      check(Math.abs(exPos() - beforePause) < 1e-6, 'resume retains position through its count-in');
      exReanchor(96); clearInterval(P.timer);
      check(Math.abs(exPos() - beforePause) < 1e-6 && exCount() > 0, 'manual tempo change retains position and count-in');
      const logs = S.exlog.length;
      now = P.startT + P.L * 60 / P.bpm + 0.01; exFrame();
      check(!P.running && P.viewPos === P.L, 'a single pass stops at the end instead of resetting');
      check(S.exlog.length === logs, 'starting partway does not log a full played pass');
      exListen(); clearInterval(P.timer); cancelAnimationFrame(P.frame);
      now = P.startT + P.L * 60 / P.bpm + 0.01; exFrame();
      check(!P.running && !P.preview && P.viewPos === P.L, 'Listen first finishes without looping');
      exOpen('transport_test',0); S.ui.exopts.count = false; exStart(); clearInterval(P.timer); cancelAnimationFrame(P.frame);
      now = P.startT + P.L * 60 / P.bpm + 0.01; exFrame();
      check(S.exlog.some(x=>x.id==='transport_test' && x.r==='played'), 'a full pass is logged');
      exOpen('triads',0); exSetSpot('1-1');
      check(P.L === 4 && P.viewPos === 0, 'section practice starts at its own beginning');
      P.labels = 'finger'; S.ui.exopts.fingers = false;
      check(window.__T.exLabel({s:0,f:3,fg:2}) === '', 'finger labels hide on the fretboard');
      S.ui.exopts.fingers = true;
      check(window.__T.exLabel({s:0,f:3,fg:2}) === '', 'None keeps the main marker empty when finger annotations are enabled');
      exStop(); delete AU.ctx.currentTime;
      return failures;
    });
    assert.deepEqual(failures, []);
    assert.deepEqual(errors, []);
    console.log('Pause/resume, scrolling, note selection, count-ins, full-pass history, twelve-key transitions, and +4 bpm loop timing\nOK');
  } finally {
    await browser.close(); fs.unlinkSync(tmp);
  }
})().catch(e => { console.error(e); process.exitCode = 1; });
